/**
 * Splits @stbr/solana-glossary into an eager metadata payload and a lazy
 * definition payload, written to src/data/generated/.
 *
 * Why this exists: the SDK ships one array where every term carries its full
 * definition, and 74% of those bytes are definition text that the home screen
 * never renders — TermCard shows a name, a category pill and two tags. Loading
 * the bare specifier therefore put ~179 kB gzip of prose on the critical path
 * for a first paint that displays none of it.
 *
 * Both payloads are emitted as `JSON.parse("…")` inside a .ts file rather than
 * as .json: TypeScript then sees a single string literal instead of inferring a
 * 1,059-entry object type, the engine takes the JSON fast path instead of
 * evaluating a giant object literal, and no tsconfig/vitest JSON plumbing is
 * needed.
 *
 * Run by `prepare` (so a fresh `npm ci` has them) and by `prebuild` (so a
 * dependency bump can never ship stale data).
 */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "src/data/generated");

const { allTerms } = require("@stbr/solana-glossary");
/* Read straight off disk: the package's `exports` map does not expose
   ./package.json, so require.resolve cannot reach it. */
const sdkVersion = JSON.parse(
  readFileSync(
    path.join(root, "node_modules/@stbr/solana-glossary/package.json"),
    "utf8",
  ),
).version;

/* `related` rides along with the metadata even though it is 9 kB gzip of ids
   the home screen never reads. Index.tsx resolves related terms during its own
   render and hands the result to TermView as a prop, so a related list that
   arrives with the lazy payload would be captured empty on a cold deep-link
   and never recomputed. Correctness beats the 9 kB. */
const META_FIELDS = [
  "id",
  "term",
  "depth",
  "category",
  "tags",
  "aliases",
  "related",
];

const meta = allTerms.map((term) => {
  const out = {};
  for (const field of META_FIELDS) {
    if (term[field] !== undefined) out[field] = term[field];
  }
  return out;
});

const definitions = {};
for (const term of allTerms) definitions[term.id] = term.definition;

/** A JS source string literal holding `value` as JSON. */
const literal = (value) => JSON.stringify(JSON.stringify(value));

const banner = (what) => `/**
 * AUTO-GENERATED by scripts/generate-glossary-payloads.mjs — do not edit.
 * Source: @stbr/solana-glossary@${sdkVersion} (${allTerms.length} terms).
 * ${what}
 */`;

mkdirSync(outDir, { recursive: true });

writeFileSync(
  path.join(outDir, "glossaryMeta.ts"),
  `${banner("Eager payload: everything the iceberg, layer cards and search list render.")}
import type { GlossaryTerm } from "@stbr/solana-glossary";

/** A glossary term minus its definition, which loads separately. */
export type TermMeta = Omit<GlossaryTerm, "definition">;

/** SDK release these payloads were generated from. */
export const GLOSSARY_SDK_VERSION = ${JSON.stringify(sdkVersion)};

export const glossaryMeta = JSON.parse(
  ${literal(meta)},
) as TermMeta[];
`,
);

writeFileSync(
  path.join(outDir, "glossaryDefinitions.ts"),
  `${banner("Lazy payload: term id -> English definition.")}
import { setDefinitions } from "../definitionStore";

export const glossaryDefinitions = JSON.parse(
  ${literal(definitions)},
) as Record<string, string>;

/* Registering at module scope — not from the importer's .then() — is what makes
   the payload usable the instant the chunk is evaluated. TermView ships in the
   same chunk, so by the time React.lazy resolves it every definition is already
   readable synchronously and no term ever paints with an empty body. */
setDefinitions(glossaryDefinitions);
`,
);

const bytes = (s) => Buffer.byteLength(s, "utf8");
console.log(
  `glossary payloads from @stbr/solana-glossary@${sdkVersion}: ` +
    `${allTerms.length} terms, meta ${bytes(JSON.stringify(meta)).toLocaleString()} B, ` +
    `definitions ${bytes(JSON.stringify(definitions)).toLocaleString()} B -> src/data/generated/`,
);
